CROSS_SCHEME_NAMES = ["MGNREGS", "State Rural Infrastructure Scheme", "State Urban Development Scheme"]


def generate_cross_scheme_dataset(df, seed=42, match_fraction=0.05, extra_unmatched=700):
    """Simulate an external cross-scheme feed (MGNREGS + state schemes) that a real
    deployment would pull via API from the respective nodal ministries/departments.
    A subset of records are constructed to overlap with existing MPLADS works
    (same district + asset category + cost within ~15% + nearby sanction window)
    to demonstrate duplicate-funding detection once that access exists.
    This is entirely SYNTHETIC_DEMO_DATA — no real MGNREGS or state-scheme data is used."""
    rng = np.random.default_rng(seed)
    n_match = max(1, int(len(df) * match_fraction))
    matched_idx = rng.choice(df.index.values, size=n_match, replace=False)
    matched_rows = df.loc[matched_idx]

    records = []
    for i, (_, row) in enumerate(matched_rows.iterrows()):
        scheme = CROSS_SCHEME_NAMES[int(rng.integers(0, len(CROSS_SCHEME_NAMES)))]
        cost_variance = rng.uniform(-0.12, 0.12)
        scheme_cost = round(float(row["cost_sanctioned"]) * (1 + cost_variance), 2)
        scheme_date = row["sanction_date"] + pd.Timedelta(days=int(rng.integers(-60, 120)))
        confidence = round(float(rng.uniform(0.68, 0.97)), 2)
        records.append({
            "scheme_record_id": f"XS{i + 1:05d}",
            "scheme": scheme,
            "state": row["state"], "district": row["district"],
            "asset_category": row["work_category"],
            "asset_description": row["work_description"],
            "cost": scheme_cost,
            "sanction_date": scheme_date.strftime("%Y-%m-%d"),
            "matched_mplads_work_id": row["work_id"],
            "match_confidence": confidence,
            "match_basis": "district + asset category + cost within ±15% + overlapping sanction window",
            "record_source": "SYNTHETIC_DEMO_DATA",
        })

    categories = df["work_category"].unique().tolist()
    states_list = df["state"].unique().tolist()
    districts_map = df.groupby("state")["district"].unique().to_dict()
    for i in range(extra_unmatched):
        st = states_list[int(rng.integers(0, len(states_list)))]
        dist_options = districts_map.get(st)
        if dist_options is None or len(dist_options) == 0:
            dist_options = [f"{st} District"]
        dist = dist_options[int(rng.integers(0, len(dist_options)))]
        cat = categories[int(rng.integers(0, len(categories)))]
        cost = round(float(rng.uniform(150000, 2500000)), 2)
        date = pd.Timestamp("2023-01-01") + pd.Timedelta(days=int(rng.integers(0, 900)))
        scheme = CROSS_SCHEME_NAMES[int(rng.integers(0, len(CROSS_SCHEME_NAMES)))]
        records.append({
            "scheme_record_id": f"XS{n_match + i + 1:05d}",
            "scheme": scheme,
            "state": st, "district": dist,
            "asset_category": cat,
            "asset_description": f"{cat} under {scheme} — {dist}",
            "cost": cost,
            "sanction_date": date.strftime("%Y-%m-%d"),
            "matched_mplads_work_id": None,
            "match_confidence": None,
            "match_basis": None,
            "record_source": "SYNTHETIC_DEMO_DATA",
        })

    matched_ids = set(matched_rows["work_id"].tolist())
    return records, matched_ids


